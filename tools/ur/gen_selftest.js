// Generates airgap_wallet/ur_selftest_vectors.h, the data for the wallet's
// on-device UR self-test (Dev tests -> UR self-test), from:
// - the upstream bc-ur vectors (vectors.json),
// - a lossy, all-mixed stream made with ur.js's encoder,
// - hostile parts (each must be refused with a given status),
// - real Sparrow captures (fixtures/), with the PSBT's SHA-256.
// Usage: node gen_selftest.js   (rerun after changing any input)
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ur = require('./ur');
const V = require('./vectors.json');

const out = [];
const cstr = (s) => JSON.stringify(s); // only ASCII here, so JSON escaping is valid C
const strArray = (name, arr) => out.push(`static const char *const ${name}[] = {\n${arr.map((s) => '  ' + cstr(s)).join(',\n')},\n};`);
const numArray = (name, type, arr) => out.push(`static const ${type} ${name}[] = {${arr.join(', ')}};`);
const makeMessage = (len, seed = 'Wolf') => new ur.Xoshiro256(seed).nextData(len);

out.push('// Generated by tools/ur/gen_selftest.js. Do not edit.');
out.push('// Upstream vectors: https://github.com/BlockchainCommons/bc-ur test/test.cpp (BSD-2-Clause-Plus-Patent).');
out.push('#pragma once');
out.push('#include <stdint.h>');

// Upstream.
out.push(`static const char *const UT_BW1_MINIMAL = ${cstr(V.bytewords1.minimal)};`);
numArray('UT_BW1_INPUT', 'uint8_t', V.bytewords1.input);
out.push(`static const char *const UT_BW1_BAD = ${cstr(V.bytewords1.badMinimal)};`);
out.push(`static const char *const UT_BW2_MINIMAL = ${cstr(V.bytewords2.minimal)};`);
numArray('UT_BW2_INPUT', 'uint8_t', V.bytewords2.input);
numArray('UT_RNG1', 'uint8_t', V.rng1);
numArray('UT_RNG2', 'uint8_t', V.rng2);
numArray('UT_RNG3', 'uint8_t', V.rng3);
numArray('UT_DEGREES', 'uint8_t', V.degrees); // seqLen = fragments of make_message(1024) at 10..100
{
  const m = makeMessage(1024);
  out.push(`static const uint32_t UT_PARTITION_SEQLEN = ${ur.partitionMessage(m, ur.findNominalFragmentLength(m.length, 10, 100)).length};`);
  out.push(`static const uint32_t UT_MSG1024_CRC = 0x${ur.crc32(m).toString(16)}u;`);
}
// Fragment sets for seqNum 1..30 as bitmasks (seqLen 11 fits in 16 bits).
numArray('UT_FRAGMENTS', 'uint16_t', V.fragments.map((set) => '0x' + set.reduce((a, i) => a | (1 << i), 0).toString(16)));
strArray('UT_UR_PARTS', V.urParts); // make_message(256) as ur:bytes, 9 fragments
out.push(`static const char *const UT_SINGLE_PART = ${cstr(V.singlePartUr)};`); // make_message(50)

// Lossy stream: 3000-byte message, 60-byte fragments (50 fragments), starting
// at seqNum 1000 (mixed parts only), 30% dropped, every kept part repeated.
{
  const msg = makeMessage(3000, 'Loss'), cbor = ur.cborBytes(msg);
  const enc = new ur.FountainEncoder(cbor, 60, 1000);
  const dec = new ur.URDecoder(), drop = new ur.Xoshiro256('drop'), parts = [];
  while (!dec.isComplete()) {
    const s = ur.encodeUrPart('bytes', enc.nextPart());
    if (drop.nextDouble() < 0.3) continue;
    parts.push(s, s);
    dec.receive(s);
  }
  if (!ur.unwrapBytes(dec.result).equals(msg)) throw new Error('lossy stream does not decode');
  const needed = parts.length / 2;
  // Margin: the device's decoder keeps at most 64 mixed parts, so it may
  // need a few more than the reference.
  for (let i = 0; i < 40; i++) {
    const s = ur.encodeUrPart('bytes', enc.nextPart());
    if (drop.nextDouble() < 0.3) continue;
    parts.push(s, s);
  }
  out.push(`// make_message(3000, "Loss"): ${parts.length / 2} distinct parts (doubled); ur.js completes after ${needed}.`);
  out.push(`static const uint32_t UT_LOSSY_JS_NEEDED = ${needed};`);
  strArray('UT_LOSSY', parts);
}

// Hostile cases: [text, expected status, description], fed one by one to a
// fresh decoder that accepts crypto-psbt and psbt only, after a valid first
// part where "after first" is set.
{
  const enc = new ur.FountainEncoder(ur.cborBytes(makeMessage(256)), 30);
  const good = ur.encodeUrPart('crypto-psbt', enc.nextPart());
  const raw = (fields) => {
    const p = { seqNum: 1, seqLen: 9, messageLen: 259, checksum: 1, data: Buffer.alloc(30), ...fields };
    return ur.bytewordsEncode(ur.encodePart(p), 'minimal');
  };
  const flip = (s) => s.slice(0, -10) + (s[s.length - 10] === 'a' ? 'e' : 'a') + s.slice(-9);
  const other = ur.encodeUrPart('crypto-psbt', new ur.FountainEncoder(ur.cborBytes(makeMessage(256, 'Other')), 30).nextPart());
  const cases = [
    ['', 'NOT_UR', 'empty'],
    ['hello world', 'NOT_UR', 'plain text'],
    ['cHNidP8BAHECAAAAAQ', 'NOT_UR', 'base64 PSBT (handled outside the UR decoder)'],
    ['ur:', 'INVALID', 'scheme only'],
    ['ur:crypto-psbt', 'INVALID', 'no body'],
    ['ur:crypto-psbt/1-9/' + good.split('/')[2] + '/x', 'INVALID', 'extra path component'],
    ['ur:crypto_psbt/' + good.split('/')[2], 'INVALID', 'bad character in type'],
    ['ur:bytes/' + good.split('/').slice(1).join('/'), 'WRONG_TYPE', 'type not accepted'],
    [flip(good), 'INVALID', 'one changed character (bytewords CRC)'],
    [good.replace('/1-9/', '/2-9/'), 'INVALID', 'sequence component lies'],
    ['ur:crypto-psbt/1-9/' + good.split('/')[2].slice(0, -1), 'INVALID', 'odd body length'],
    ['ur:crypto-psbt/x-9/' + good.split('/')[2], 'INVALID', 'non-numeric seqNum'],
    ['ur:crypto-psbt/99999999999-9/' + good.split('/')[2], 'INVALID', 'seqNum overflow'],
    ['ur:crypto-psbt/0-9/' + raw({ seqNum: 0 }), 'INVALID', 'seqNum 0'],
    ['ur:crypto-psbt/1-0/' + raw({ seqLen: 0 }), 'INVALID', 'seqLen 0'],
    ['ur:crypto-psbt/1-9/' + raw({ messageLen: 1000 }), 'INVALID', 'seqLen != ceil(messageLen / fragmentLen)'],
    ['ur:crypto-psbt/1-2185/' + raw({ seqLen: 2185, messageLen: 65550 }), 'TOO_LARGE', 'message over 64 KB'],
    ['ur:crypto-psbt/1-2000/' + raw({ seqLen: 2000, messageLen: 60000 }), 'TOO_LARGE', 'more than 1024 fragments'],
    ['ur:crypto-psbt/' + ur.bytewordsEncode(Buffer.from([0x41, 0x00]), 'minimal'), 'COMPLETE', 'single part (any bytes: the CBOR is checked later)'],
  ];
  const after = [
    [other, 'OTHER_MESSAGE', 'part of a different message'],
    [good, 'DUPLICATE', 'same part again'],
    [good.toUpperCase(), 'DUPLICATE', 'same part, upper case'],
    ['ur:psbt/' + good.split('/').slice(1).join('/'), 'WRONG_TYPE', 'accepted type, but not the first part\'s'],
    ['ur:crypto-psbt/' + ur.bytewordsEncode(Buffer.from([0x41, 0x00]), 'minimal'), 'OTHER_MESSAGE', 'single part during a multipart message'],
  ];
  out.push(`static const char *const UT_HOSTILE_FIRST = ${cstr(good)};`);
  const emit = (name, list) => out.push(`static const UrCase ${name}[] = {\n${list.map(([t, st, d]) => `  {${cstr(t)}, ur::${st}, ${cstr(d)}}`).join(',\n')},\n};`);
  out.push('struct UrCase { const char *text; ur::Status want; const char *what; };');
  emit('UT_HOSTILE', cases);
  emit('UT_HOSTILE_AFTER', after);
}

// Real Sparrow captures (Sparrow 2.5.5, signet test wallet). Each group is
// fed in capture order until complete; all must give the same PSBT.
{
  const lines = fs.readFileSync(path.join(__dirname, 'fixtures', 'sparrow_psbt_2026-10-29_a.txt'), 'utf8').split('\n').filter(Boolean)
    .map((l) => l.slice(l.indexOf(' ') + 1));
  const groups = new Map();
  for (const f of lines) {
    const k = f.split('/')[1].split('-')[1];
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(f);
  }
  let digest = null, len = 0, n = 0;
  for (const [k, fr] of groups) {
    const d = new ur.URDecoder(), used = [];
    for (const f of fr) { if (d.isComplete()) break; d.receive(f); used.push(f); }
    if (!d.isComplete()) throw new Error('capture group incomplete');
    const psbt = ur.unwrapBytes(d.result);
    const h = crypto.createHash('sha256').update(psbt).digest('hex');
    if (digest && h !== digest) throw new Error('captures disagree');
    digest = h; len = psbt.length;
    strArray(`UT_SPARROW_${k}`, used);
    n++;
  }
  out.push(`static const uint32_t UT_SPARROW_PSBT_LEN = ${len};`);
  numArray('UT_SPARROW_PSBT_SHA256', 'uint8_t', [...Buffer.from(digest, 'hex')].map((b) => '0x' + b.toString(16)));
  if (n !== 2) throw new Error('expected two density groups');
}

const dest = path.join(__dirname, '..', '..', 'airgap_wallet', 'ur_selftest_vectors.h');
fs.writeFileSync(dest, out.join('\n') + '\n');
console.log(`wrote ${dest} (${fs.statSync(dest).size} bytes)`);
